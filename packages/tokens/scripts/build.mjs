import StyleDictionary from 'style-dictionary';

const header = '/* Generated by Style Dictionary from src/primitives/*.json. Do not edit. */\n';

/** Builds the nested object (by token path) with the resolved values. */
function toNested(tokens) {
  const root = {};
  for (const token of tokens) {
    let node = root;
    token.path.forEach((key, i) => {
      if (i === token.path.length - 1) node[key] = token.value;
      else node = node[key] ??= {};
    });
  }
  return root;
}

/** Builds the literal type of the nested object (readonly string literals). */
function toType(node, indent = '') {
  if (typeof node !== 'object') return JSON.stringify(String(node));
  const inner = `${indent}  `;
  const lines = Object.entries(node).map(
    ([k, v]) => `${inner}readonly ${JSON.stringify(k)}: ${toType(v, inner)};`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

const nested = (dictionary) =>
  toNested(dictionary.allTokens.map((t) => ({ path: t.path, value: String(t.value) })));

StyleDictionary.registerFormat({
  name: 'ds/js-esm',
  format: ({ dictionary }) =>
    `${header}export const tokens = ${JSON.stringify(nested(dictionary), null, 2)};\n`,
});
StyleDictionary.registerFormat({
  name: 'ds/js-cjs',
  format: ({ dictionary }) =>
    `${header}"use strict";\nconst tokens = ${JSON.stringify(nested(dictionary), null, 2)};\nmodule.exports = { tokens };\n`,
});
StyleDictionary.registerFormat({
  name: 'ds/dts',
  format: ({ dictionary }) =>
    `${header}export declare const tokens: ${toType(nested(dictionary))};\nexport type Tokens = typeof tokens;\n`,
});

const sd = new StyleDictionary({
  source: ['src/primitives/*.json'],
  log: { verbosity: 'silent', warnings: 'error' },
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'ds',
      buildPath: 'dist/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: {
            selector: ':root',
            outputReferences: false,
            fileHeader: () => [
              'Generated by Style Dictionary from src/primitives/*.json. Do not edit.',
            ],
          },
        },
      ],
    },
    js: {
      transformGroup: 'js',
      buildPath: 'dist/',
      files: [
        { destination: 'index.js', format: 'ds/js-esm' },
        { destination: 'index.cjs', format: 'ds/js-cjs' },
        { destination: 'index.d.ts', format: 'ds/dts' },
      ],
    },
  },
});

await sd.cleanAllPlatforms();
await sd.buildAllPlatforms();
