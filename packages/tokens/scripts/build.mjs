import { mkdirSync, writeFileSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';

const header = '/* Generated by Style Dictionary from src/primitives/*.json. Do not edit. */\n';

/** Builds the nested object (by token path) with the resolved values. */
function toNested(tokens) {
  const root = {};
  for (const token of tokens) {
    let node = root;
    token.path.forEach((key, i) => {
      if (i === token.path.length - 1) node[key] = token.value;
      else node = node[key] ??= {};
    });
  }
  return root;
}

/** Builds the literal type of the nested object (readonly string literals). */
function toType(node, indent = '', widen = false) {
  if (typeof node !== 'object') return widen ? 'string' : JSON.stringify(String(node));
  const inner = `${indent}  `;
  const lines = Object.entries(node).map(
    ([k, v]) => `${inner}readonly ${JSON.stringify(k)}: ${toType(v, inner, widen)};`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

const nested = (dictionary) =>
  toNested(dictionary.allTokens.map((t) => ({ path: t.path, value: String(t.value) })));

/** Adds an alpha channel (token property `alpha`) to an already resolved hex colour. */
StyleDictionary.registerTransform({
  name: 'ds/color/alpha',
  type: 'value',
  transitive: true,
  filter: (token) => typeof token.alpha === 'number',
  transform: (token) => {
    const hex = String(token.value).replace('#', '').slice(0, 6);
    const alpha = Math.round(token.alpha * 255)
      .toString(16)
      .padStart(2, '0');
    return `#${hex}${alpha}`;
  },
});
StyleDictionary.registerTransformGroup({
  name: 'ds/css',
  transforms: [...StyleDictionary.hooks.transformGroups.css, 'ds/color/alpha'],
});

/** Resolves one semantic theme (primitives are only used to resolve references). */
async function buildTheme(name) {
  const themeSd = new StyleDictionary({
    include: ['src/primitives/*.json'],
    source: [`src/semantic/${name}.json`],
    log: { verbosity: 'silent', warnings: 'error' },
    platforms: { css: { transformGroup: 'ds/css', prefix: 'ds' } },
  });
  const { allTokens } = await themeSd.getPlatformTokens('css');
  return allTokens.filter((t) => t.isSource);
}

const themeTokens = { light: await buildTheme('light'), dark: await buildTheme('dark') };
const themes = Object.fromEntries(
  Object.entries(themeTokens).map(([name, list]) => [
    name,
    toNested(list.map((t) => ({ path: t.path, value: String(t.value) }))),
  ]),
);

const declarations = (name, indent) =>
  [
    `${indent}color-scheme: ${name};`,
    ...themeTokens[name].map((t) => `${indent}--${t.name}: ${t.value};`),
  ].join('\n');

const themesCss = `/* Generated by Style Dictionary from src/semantic/*.json. Do not edit. */
:root,
[data-theme="light"] {
${declarations('light', '  ')}
}

[data-theme="dark"] {
${declarations('dark', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${declarations('dark', '    ')}
  }
}
`;

const themesJson = JSON.stringify(themes, null, 2);

StyleDictionary.registerFormat({
  name: 'ds/js-esm',
  format: ({ dictionary }) =>
    `${header}export const tokens = ${JSON.stringify(nested(dictionary), null, 2)};\nexport const themes = ${themesJson};\n`,
});
StyleDictionary.registerFormat({
  name: 'ds/js-cjs',
  format: ({ dictionary }) =>
    `${header}"use strict";\nconst tokens = ${JSON.stringify(nested(dictionary), null, 2)};\nconst themes = ${themesJson};\nmodule.exports = { tokens, themes };\n`,
});
StyleDictionary.registerFormat({
  name: 'ds/dts',
  format: ({ dictionary }) =>
    `${header}export declare const tokens: ${toType(nested(dictionary))};\nexport type Tokens = typeof tokens;\nexport declare const themes: {\n  readonly light: ${toType(themes.light, '  ', true)};\n  readonly dark: ${toType(themes.dark, '  ', true)};\n};\nexport type Themes = typeof themes;\n`,
});

const sd = new StyleDictionary({
  source: ['src/primitives/*.json'],
  log: { verbosity: 'silent', warnings: 'error' },
  platforms: {
    css: {
      transformGroup: 'css',
      prefix: 'ds',
      buildPath: 'dist/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: {
            selector: ':root',
            outputReferences: false,
            fileHeader: () => [
              'Generated by Style Dictionary from src/primitives/*.json. Do not edit.',
            ],
          },
        },
      ],
    },
    js: {
      transformGroup: 'js',
      buildPath: 'dist/',
      files: [
        { destination: 'index.js', format: 'ds/js-esm' },
        { destination: 'index.cjs', format: 'ds/js-cjs' },
        { destination: 'index.d.ts', format: 'ds/dts' },
      ],
    },
  },
});

await sd.cleanAllPlatforms();
await sd.buildAllPlatforms();
mkdirSync('dist', { recursive: true });
writeFileSync('dist/themes.css', themesCss);
