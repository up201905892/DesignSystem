// Copies the chosen Lucide icons into svg/ and converts them to React components
// in src/generated/ with SVGR. Running it twice produces no changes.
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from '@svgr/core';
import jsxPlugin from '@svgr/plugin-jsx';
import prettier from 'prettier';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const lucideIcons = join(dirname(require.resolve('lucide-static/package.json')), 'icons');

// prettier-ignore
const ICONS = [
  'check', 'x', 'minus', 'plus', 'chevron-down', 'chevron-up', 'chevron-left', 'chevron-right',
  'chevrons-up-down', 'arrow-up', 'arrow-down', 'arrow-up-down', 'info', 'circle-check',
  'circle-alert', 'triangle-alert', 'circle-x', 'search', 'ellipsis', 'eye', 'eye-off', 'sun',
  'moon', 'loader-circle', 'external-link', 'menu', 'trash-2', 'pencil', 'settings', 'user',
];

const toComponentName = (file) =>
  file
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('') + 'Icon';

// Keeps only the inner shapes: the <svg> wrapper (size, stroke, a11y) lives in IconBase.
const stripRoot = (source) => source.replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[^>]*>/, '<svg>');

const template = ({ componentName, jsx }, { tpl }) => {
  return tpl`
    import { forwardRef } from 'react';
    import { IconBase, type IconProps } from '../IconBase';

    export const ${componentName} = forwardRef<SVGSVGElement, IconProps>((props, ref) => (
      ${jsx}
    ));
    ${componentName}.displayName = '${componentName}';
  `;
};

const prettierOptions = {
  ...(await prettier.resolveConfig(join(root, '../../.prettierrc'))),
  parser: 'typescript',
};
const format = (code) => prettier.format(code, prettierOptions);

const svgDir = join(root, 'svg');
const outDir = join(root, 'src/generated');
await mkdir(svgDir, { recursive: true });
for (const name of ICONS) {
  await copyFile(join(lucideIcons, `${name}.svg`), join(svgDir, `${name}.svg`));
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const files = (await readdir(svgDir)).filter((f) => f.endsWith('.svg')).sort();
const exportsList = [];
for (const file of files) {
  const base = file.replace(/\.svg$/, '');
  const componentName = toComponentName(base);
  const svgrOutput = await transform(
    stripRoot(await readFile(join(svgDir, file), 'utf8')),
    { plugins: [jsxPlugin], typescript: true, ref: true, expandProps: 'end', template },
    { componentName },
  );
  // SVGR adds ref and props to the <svg> root; swap it for the shared wrapper.
  const code = svgrOutput.replace('<svg', '<IconBase').replace('</svg>', '</IconBase>');
  await writeFile(
    join(outDir, `${componentName}.tsx`),
    await format(`// Generated by scripts/generate.mjs from svg/${file}. Do not edit.\n${code}`),
  );
  exportsList.push(componentName);
}

const index = [
  '// Generated by scripts/generate.mjs. Do not edit.',
  "export type { IconProps } from './IconBase';",
  ...exportsList.map((n) => `export { ${n} } from './generated/${n}';`),
  '',
].join('\n');
await writeFile(join(root, 'src/index.ts'), await format(index));
